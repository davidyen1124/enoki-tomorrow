// Real-mode smoke test: intro, skip button, resize rebuild, restart button.
import { chromium } from 'playwright';
const url = process.env.URL || 'http://localhost:5199/';
const browser = await chromium.launch();
const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
await page.goto(url, { waitUntil: 'networkidle' });
await page.waitForTimeout(2200);
await page.screenshot({ path: 'shots/f/live_1_intro.png' });
await page.click('[data-skip]');
await page.waitForTimeout(4500);
const y1 = await page.evaluate(() => scrollY);
await page.screenshot({ path: 'shots/f/live_2_skip.png' });
await page.setViewportSize({ width: 700, height: 900 });
await page.waitForTimeout(1800);
await page.screenshot({ path: 'shots/f/live_3_resized.png' });
await page.setViewportSize({ width: 1440, height: 900 });
await page.waitForTimeout(1800);
await page.evaluate(() => window.scrollTo(0, document.documentElement.scrollHeight));
await page.waitForTimeout(1200);
await page.evaluate(() => window.scrollTo(0, document.querySelector('.finale').offsetTop));
await page.waitForTimeout(1500);
await page.click('[data-again]');
await page.waitForTimeout(4000);
const y2 = await page.evaluate(() => scrollY);
await page.screenshot({ path: 'shots/f/live_4_again.png' });
console.log('after skip scrollY', y1, '| after restart scrollY', y2, '| errors', errors.length ? errors : 'none');
await browser.close();
